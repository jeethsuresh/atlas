const assert = require('node:assert/strict');
const History = require('../web/navigation-history.js');
const h = new History({view:'home'}, 2);
assert.equal(h.back(), null);
assert.equal(h.forward(), null);
h.visit({view:'list'}); h.visit({view:'detail'});
assert.deepEqual(h.back(), {view:'list'});
assert.deepEqual(h.back(), {view:'home'});
assert.deepEqual(h.forward(), {view:'list'});
h.visit({view:'new'});
assert.equal(h.forward(), null);
h.visit({view:'next'});h.visit({view:'last'});
assert.deepEqual(h.back(), {view:'next'});
assert.deepEqual(h.back(), {view:'new'});
assert.equal(h.back(), null);
h.reset({view:'other account'});
assert.equal(h.forward(), null);
assert.equal(h.back(), null);
console.log('Navigation history tests passed');
